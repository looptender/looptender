#!/usr/bin/env python3
"""Deterministically package canonical continuity modules; --check refuses drift."""
import ast
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parent
NAMES = ('project_work.py', 'coordinator_coverage.py', 'coordinator.py', 'coordinator_state.py')

def generate():
    stream = io.BytesIO()
    hashes, tokens, codes, actions = {}, set(), {"source_drift", "source_unavailable", "dependency_cycle"}, {"reconcile_bound_coverage"}
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_STORED) as archive:
        for name in NAMES:
            raw = (ROOT / 'skills/keepgoing/scripts' / name).read_bytes()
            hashes[name] = hashlib.sha256(raw).hexdigest()
            tree = ast.parse(raw)
            def strings(expr):
                return {n.value for n in ast.walk(expr) if isinstance(n, ast.Constant) and isinstance(n.value, str) and re.fullmatch('[a-z][a-z0-9_]*', n.value)}
            if name in ('project_work.py', 'coordinator_coverage.py'):
                for node in ast.walk(tree):
                    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in ('finding', 'unknown'):
                        if node.args: codes.update(strings(node.args[0]))
                        if len(node.args) > 2: actions.update(strings(node.args[2]))
                        for kw in node.keywords:
                            if kw.arg == 'action': actions.update(strings(kw.value))
                    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'reason' for t in node.targets):
                        codes.update(strings(node.value))
                    # Missing inputs can be appended directly, without finding/unknown.
                    # Extract the canonical reason role, not unrelated global literals.
                    if isinstance(node, ast.Dict):
                        for key, value in zip(node.keys, node.values):
                            if isinstance(key, ast.Constant) and key.value == 'reason':
                                codes.update(strings(value))
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, str) and re.fullmatch('[a-z][a-z0-9_]*', node.value):
                    tokens.add(node.value)
            info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
            info.create_system = 3  # Stable Unix metadata even when drift checks run on Windows.
            info.external_attr = 0o100600 << 16
            archive.writestr(info, raw)
        info = zipfile.ZipInfo('__main__.py', (1980, 1, 1, 0, 0, 0))
        info.create_system = 3
        info.external_attr = 0o100600 << 16
        archive.writestr(info, b'import project_work\nraise SystemExit(project_work.main())\n')
    raw = stream.getvalue()
    return ('// Generated by continuity-host-inspector-generate.py; do not edit.\n'
            + 'export const continuityHelperBase64 = ' + json.dumps(base64.b64encode(raw).decode()) + ';\n'
            + 'export const continuityHelperSha256 = ' + json.dumps(hashlib.sha256(raw).hexdigest()) + ';\n'
            + 'export const continuityHelperSources = ' + json.dumps(hashes, sort_keys=True) + ' as const;\n'
            + '// Literal vocabulary only; this is not a second WORK validator. Unknown output fails closed.\n'
            + 'export const continuityHelperTokens: readonly string[] = ' + json.dumps(sorted(tokens)) + ';\n'
            + 'export const continuityHelperCodes: readonly string[] = ' + json.dumps(sorted(codes)) + ';\n'
            + 'export const continuityHelperActions: readonly string[] = ' + json.dumps(sorted(actions)) + ';\n').encode()

if __name__ == '__main__':
    target = ROOT / 'continuity-host-inspector-asset.ts'
    expected = generate()
    if sys.argv[1:] == ['--check']:
        if not target.exists() or target.read_bytes() != expected:
            raise SystemExit('continuity_helper_source_drift')
    elif not sys.argv[1:]:
        target.write_bytes(expected)
    else:
        raise SystemExit('usage: continuity-host-inspector-generate.py [--check]')
